use crate::prober;
use anyhow::Result;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::Arc;
use tokio::sync::Semaphore;
use tracing::{info, warn};

pub struct TestConfig {
    pub input: String,
    pub domain: String,
    pub output: Option<String>,
}

/// Result for a single resolver reachability test.
#[derive(Debug)]
struct TestResult {
    name: String,
    ip: String,
    doh: Option<String>,
    reachable: bool,
    latency_ms: Option<u64>,
}

/// Run the test command — quick reachability check.
pub async fn run_test(config: TestConfig) -> Result<()> {
    // Parse input TOML (same format as resolvers.toml)
    let content = tokio::fs::read_to_string(&config.input).await?;
    let parsed: sp_common::config::Config = toml::from_str(&content)?;
    let endpoints = parsed.all_endpoints();

    info!("testing {} endpoints from {}", endpoints.len(), config.input);

    let sem = Arc::new(Semaphore::new(10));
    let total = endpoints.len();
    let done = Arc::new(AtomicUsize::new(0));

    let mut handles = Vec::new();

    for ep in endpoints {
        let domain = config.domain.clone();
        let sem = sem.clone();
        let done = done.clone();

        let handle = tokio::spawn(async move {
            let _permit = sem.acquire().await.unwrap();

            let result = prober::probe_resolver(
                &ep.ip,
                ep.doh_url.as_deref(),
                &domain,
            )
            .await;

            let d = done.fetch_add(1, Ordering::Relaxed) + 1;
            eprint!("\r[{}/{}] testing...    ", d, total);

            TestResult {
                name: ep.name,
                ip: ep.ip,
                doh: ep.doh_url,
                reachable: result.alive,
                latency_ms: result.latency_ms,
            }
        });
        handles.push(handle);
    }

    let mut results = Vec::new();
    for handle in handles {
        match handle.await {
            Ok(r) => results.push(r),
            Err(e) => warn!("task error: {}", e),
        }
    }

    eprintln!();

    // Filter reachable and sort by latency
    let mut reachable: Vec<&TestResult> = results.iter().filter(|r| r.reachable).collect();
    reachable.sort_by_key(|r| r.latency_ms.unwrap_or(u64::MAX));

    info!(
        "test complete: {}/{} reachable",
        reachable.len(),
        results.len()
    );

    // Write output TOML
    let output_path = config
        .output
        .unwrap_or_else(|| "resolvers-local.toml".to_string());

    let mut toml_out = String::from("# Reachable resolvers — generated by dns-scanner test\n\n");
    for r in &reachable {
        toml_out.push_str("[[resolver]]\n");
        toml_out.push_str(&format!("name = \"{}\"\n", r.name));
        toml_out.push_str(&format!("ip = [\"{}\"]\n", r.ip));
        if let Some(ref doh) = r.doh {
            toml_out.push_str(&format!("doh = \"{}\"\n", doh));
        }
        if let Some(lat) = r.latency_ms {
            toml_out.push_str(&format!("# latency: {}ms\n", lat));
        }
        toml_out.push('\n');
    }

    tokio::fs::write(&output_path, toml_out).await?;
    info!("wrote {} reachable resolvers to {}", reachable.len(), output_path);

    Ok(())
}
